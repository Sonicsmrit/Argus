/**
 * Calculates the bilateral sanctions risk between two countries based on the user's applicable regimes.
 * @param {string} fromCountry - ISO alpha-2 country code of the user/entity initiating the check
 * @param {string} toCountry - ISO alpha-2 country code of the target
 * @returns {object} { regimes: Array, overallRisk: number, overallLevel: string }
 */
export function getBilateralRisk(fromCountry, toCountry) {
  if (!fromCountry || !toCountry) return null;
  
  const fromCode = fromCountry.toUpperCase();
  const toCode = toCountry.toUpperCase();
  
  const applicableRegimes = COUNTRY_TO_REGIMES[fromCode] || ['UN'];
  
  const assessments = [];
  let maxRisk = 0;
  let highestLevel = 'NONE';
  
  const levelRank = {
    'NONE': 0,
    'TARGETED': 1,
    'ARMS_EMBARGO': 2,
    'SECTORAL': 3,
    'COMPREHENSIVE': 4
  };

  applicableRegimes.forEach(regime => {
    if (SANCTIONS_PROGRAMS[regime] && SANCTIONS_PROGRAMS[regime][toCode]) {
      const programData = SANCTIONS_PROGRAMS[regime][toCode];
      assessments.push({
        regime,
        ...programData
      });
      
      if (programData.riskScore > maxRisk) {
        maxRisk = programData.riskScore;
      }
      
      if (levelRank[programData.level] > levelRank[highestLevel]) {
        highestLevel = programData.level;
      }
    }
  });

  return {
    regimes: assessments,
    overallRisk: maxRisk,
    overallLevel: highestLevel
  };
}
