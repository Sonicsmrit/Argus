export const getShortName = (code) => {
  const c = String(code || '').toUpperCase();
  if (SHORT_NAME_OVERRIDES[c]) return SHORT_NAME_OVERRIDES[c];
  const full = COUNTRY_NAMES[c];
  if (!full) return c;
  return full.replace(/\s*\([^)]*\)\s*/g, ' ').replace(/\s+/g, ' ').trim();
};

